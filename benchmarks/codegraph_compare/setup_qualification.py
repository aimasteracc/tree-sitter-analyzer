@dataclass(frozen=True)
class OracleSpecV1:
    oracle_id: str
    kind: str
    query: tuple[tuple[str, str], ...]
    expected_result: Any

    def __post_init__(self) -> None:
        if self.kind not in {"symbol", "call"} or not self.oracle_id:
            raise ValueError("Oracle must be a named symbol or call query")
        if not self.query or self.query != tuple(sorted(set(self.query))):
            raise ValueError("Oracle parameters must be sorted and unique")

    @property
    def digest(self) -> str:
        return _sha256(asdict(self))


def _is_finite_number(value: object) -> bool:
    """Check JSON numbers without converting arbitrary-size integers to float."""
    return type(value) is int or (type(value) is float and math.isfinite(value))


@dataclass(frozen=True)
class ResourcePlanV1:
    wall_timeout_seconds: int
    max_cpu_seconds: int
    max_index_bytes: int
    max_disk_write_bytes: int
    min_free_disk_bytes: int
    max_rss_bytes: int
    max_processes: int
    max_open_files: int
    max_concurrency: int = 1

    def __post_init__(self) -> None:
        values = tuple(asdict(self).values())
        if (
            any(not _is_finite_number(value) or value <= 0 for value in values)
            or not isinstance(self.max_concurrency, int)
            or isinstance(self.max_concurrency, bool)
            or self.max_concurrency != 1
        ):
            raise ValueError(
                "Every resource ceiling must be positive; concurrency is exactly one"
            )

    @property
    def digest(self) -> str:
        return _sha256(asdict(self))


@dataclass(frozen=True)
class HarnessArtifactV1:
    path: str
    size_bytes: int
    sha256: str

    @classmethod
    def read(cls, path: Path) -> HarnessArtifactV1:
        absolute = path.absolute()
        if not absolute.is_absolute():
            raise ValueError("Harness artifact must have an absolute path")
        payload = _read_regular_beneath(
            Path(absolute.anchor), absolute.as_posix().lstrip("/")
        )
        return cls(str(absolute), len(payload), _bytes_hash(payload))


@dataclass(frozen=True)
class ExecutionSpecV1:
    """One exact external command frozen by the trusted plan."""

    execution_id: str
    argv: tuple[str, ...]

    def __post_init__(self) -> None:
        if (
            not isinstance(self.execution_id, str)
            or not self.execution_id
            or not self.argv
            or any(not isinstance(arg, str) or not arg for arg in self.argv)
        ):
            raise ValueError("Execution IDs and argv entries must be non-empty")


@dataclass(frozen=True)
class CellPlanV1:
    repo_id: str
    arm_id: str
    attempt: int
    artifact_path: str
    eligibility: EligibilityV1
    tool: HarnessArtifactV1
    config: HarnessArtifactV1
    oracle_specs: tuple[OracleSpecV1, ...]
    resources: ResourcePlanV1
    executions: tuple[ExecutionSpecV1, ...]
    parse_error_allowlist: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        if (self.repo_id, self.arm_id) not in EXPECTED_CELLS or self.attempt != 1:
            raise ValueError("Plan identity must be a canonical cell at attempt 1")
        canonical_relative_path(self.artifact_path)
        if self.eligibility.repo_id != self.repo_id:
            raise ValueError("Eligibility is not bound to the planned repository")
        oracle_ids = tuple(spec.oracle_id for spec in self.oracle_specs)
        if {spec.kind for spec in self.oracle_specs} != {"symbol", "call"} or len(
            oracle_ids
        ) != len(set(oracle_ids)):
            raise ValueError("Each plan requires unique symbol and call oracle IDs")
        execution_ids = tuple(spec.execution_id for spec in self.executions)
        if execution_ids != ("delete", "build", "health", *oracle_ids):
            raise ValueError(
                "Plan must freeze ordered delete/build/health/symbol/call executions"
            )
        allowlist = _sorted_paths(self.parse_error_allowlist, "parse-error allowlist")
        if not set(allowlist).issubset(self.eligibility.eligible_paths):
            raise ValueError(
                "Parse-error allowlist must be pre-registered eligible paths"
            )

    @property
    def digest(self) -> str:
        return _sha256(asdict(self))


def _git(repo: Path, *arguments: str, input: bytes | None = None) -> bytes:
    return subprocess.run(
        ["git", *arguments],
        cwd=repo,
        input=input,
        capture_output=True,
        check=True,
        timeout=_GIT_TIMEOUT_SECONDS,
    ).stdout


def _tracked_stage(repo: Path) -> tuple[tuple[str, str, str], ...]:
    records = []
    for raw in _git(repo, "ls-files", "-z", "--stage").split(b"\0"):
        if not raw:
            continue
        try:
            metadata, encoded = raw.split(b"\t", 1)
            mode, object_id, stage = metadata.decode("ascii").split(" ")
            relative = canonical_relative_path(encoded.decode("utf-8"))
        except (UnicodeDecodeError, ValueError) as exc:
            raise ValueError(
                "Malformed, non-UTF-8, or non-canonical tracked path"
            ) from exc
        if stage != "0":
            raise ValueError("Only stage-zero tracked paths are allowed")
        records.append((relative, mode, object_id))
    records.sort()
    if len({item[0] for item in records}) != len(records):
        raise ValueError("Duplicate tracked paths")
    return tuple(records)


def inventory_sources(repo_id: str, repo: Path, rules: SourceRulesV1) -> EligibilityV1:
    """Compute the complete plan-bound source partition from Git and worktree bytes."""
    records = _tracked_stage(repo)
    commit = _git(repo, "rev-parse", "HEAD").decode("ascii").strip()
    if _git(repo, "status", "--porcelain", "--untracked-files=no"):
        raise ValueError("Tracked qualification checkout is dirty")
    regular: list[str] = []
    eligible: list[str] = []
    excluded: list[tuple[str, str]] = []
    file_hashes: list[tuple[str, str, str, str]] = []
    extensions = rules.extensions(repo_id)
    for relative, mode, object_id in records:
        if mode in {"160000", "120000"}:
            excluded.append((relative, "gitlink" if mode == "160000" else "symlink"))
            continue
        if mode not in _REGULAR_MODES:
            raise ValueError(f"Unsupported tracked mode {mode}: {relative}")
        # Qualification reads the immutable stage-zero object, never mutable
        # worktree bytes. Verify Git still identifies those exact bytes.
        payload = _git(repo, "cat-file", "blob", object_id)
        verified_object_id = (
            _git(repo, "hash-object", "--stdin", input=payload).decode("ascii").strip()
        )
        if verified_object_id != object_id:
            raise ValueError(f"Pinned Git object mismatch: {relative}")
        regular.append(relative)
        file_hashes.append((relative, mode, object_id, _bytes_hash(payload)))
        components = relative.split("/")
        reason = None
        if PurePosixPath(relative).suffix not in extensions:
            reason = "extension"
        elif any(part in rules.excluded_components for part in components[:-1]):
            reason = "excluded-component"
        elif any(relative.endswith(suffix) for suffix in rules.minified_suffixes):
            reason = "minified"
        elif any(marker in payload[:4096] for marker in rules.generated_markers):
            reason = "generated"
        if reason is None:
            eligible.append(relative)
        else:
            excluded.append((relative, reason))
    if _git(repo, "status", "--porcelain", "--untracked-files=no"):
        raise ValueError("Tracked qualification checkout changed during inventory")
    if (
        _tracked_stage(repo) != records
        or _git(repo, "rev-parse", "HEAD").decode("ascii").strip() != commit
    ):
        raise ValueError("Pinned Git objects changed during inventory")
    eligible_paths = tuple(eligible)
    return EligibilityV1(
        repo_id,
        rules.digest,
        commit,
        tuple(regular),
        eligible_paths,
        tuple(sorted(excluded)),
        _sha256([(p, m, oid) for p, m, oid in records]),
        _sha256(list(eligible_paths)),
        _sha256(
            {
                "commit": commit,
                "inventory": [(p, m, oid) for p, m, oid in records],
                "files": file_hashes,
            }
        ),
    )


def _sorted_paths(paths: Sequence[str], name: str) -> tuple[str, ...]:
    value = tuple(canonical_relative_path(path) for path in paths)
    if value != tuple(sorted(set(value))):
        raise ValueError(f"{name} paths must be sorted and unique")
    return value


