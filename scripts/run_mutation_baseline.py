RATCHET_PATH = Path("tests/effectiveness/mutation_ratchet.json")
STATS_PATH = Path("mutants/mutmut-cicd-stats.json")

PYPROJECT_TEMPLATE = """\
# Temporary pyproject.toml for per-module mutmut run (generated by scripts/run_mutation_baseline.py).
# Do not edit — regenerated on each run.
[tool.mutmut]
source_paths = ["{source_path}"]
# 被测模块的包内依赖（如 ast_diff 引用的 .core.parser、.project_graph）
# 必须一并拷进 mutmut 沙盒，否则 mutants/ 里只有被测文件本身，
# 导入链断裂、全部变异 not checked（2026-07 大重构后引入的回归）。
also_copy = ["tree_sitter_analyzer"]
pytest_add_cli_args_test_selection = {test_paths_toml}
pytest_add_cli_args = ["-n", "0", "-x", "--timeout=30", "-q"]
timeout_multiplier = 10.0
timeout_constant = 10.0
"""


class MutationReportError(RuntimeError):
    """mutmut finished without a usable stats report."""


def _resolve_mutmut_command() -> list[str]:
    """Return a direct mutmut command from the already-resolved environment."""
    current_env_script = Path(sys.executable).with_name("mutmut")
    if current_env_script.exists():
        return [str(current_env_script)]
    path_script = shutil.which("mutmut")
    if path_script:
        return [path_script]
    return [sys.executable, "-m", "mutmut"]


def run_module(module_key: str, repo_root: Path) -> None:
    if module_key not in MODULES:
        print(f"Unknown module: {module_key}. Choose from: {list(MODULES)}")
        sys.exit(1)

    source_path, test_paths = MODULES[module_key]
    test_paths_toml = "[" + ", ".join(f'"{p}"' for p in test_paths) + "]"

    # Resolve mutmut before swapping pyproject.toml. The runner is usually
    # invoked via ``uv run python ...``; calling ``uv run`` again inside the
    # swap window would make uv resolve from the temporary minimal pyproject.
    mutmut_command = _resolve_mutmut_command()

    # mutmut 3.6 only reads config from CWD pyproject.toml / setup.cfg and has
    # no config-file CLI flag. Swap only for mutmut's direct process.
    real_pyproject = repo_root / "pyproject.toml"

    content = PYPROJECT_TEMPLATE.format(
        source_path=source_path,
        test_paths_toml=test_paths_toml,
    )

    with tempfile.TemporaryDirectory(prefix="mutation-baseline-") as temp_dir:
        temp_root = Path(temp_dir)
        backup = temp_root / "pyproject.toml"
        minimal_pyproject = temp_root / "pyproject.mutmut.toml"
        minimal_pyproject.write_text(content, encoding="utf-8")
        shutil.copy2(real_pyproject, backup)
        try:
            shutil.copy2(minimal_pyproject, real_pyproject)
            print(f"\n=== Running mutmut on {source_path} ===")
            print(f"    Tests: {test_paths}")
            result = subprocess.run(
                [*mutmut_command, "run"],
                cwd=repo_root,
                capture_output=False,
            )
            print(f"\n=== mutmut run exit code: {result.returncode} ===")
            result.check_returncode()

            # 仅在变异运行成功后读取结果；读取失败同样必须向入口传播。
            # export-cicd-stats 也读 [tool.mutmut]，必须在替换窗口内运行。
            for step in ("results", "export-cicd-stats"):
                if step == "results":
                    print(f"\n=== Results for {module_key} ===")
                result = subprocess.run(
                    [*mutmut_command, step],
                    cwd=repo_root,
                )
                result.check_returncode()
        finally:
            shutil.copy2(backup, real_pyproject)


def read_stats(repo_root: Path) -> dict[str, Any]:
    """mutmut's exported CI stats; a missing or empty report is a failure."""
    path = repo_root / STATS_PATH
    if not path.is_file():
        raise MutationReportError(f"mutmut produced no stats report at {STATS_PATH}")
    stats = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(stats, dict) or not isinstance(stats.get("total"), int):
        raise MutationReportError(f"malformed mutmut stats report: {stats!r}")
    return stats


def unkilled(stats: dict[str, Any]) -> int:
    """Mutants the selected tests did not kill: survivors plus untested ones."""
    return int(stats.get("survived", 0)) + int(stats.get("no_tests", 0))


def load_ratchet(repo_root: Path) -> dict[str, int]:
    data = json.loads((repo_root / RATCHET_PATH).read_text(encoding="utf-8"))
    modules = data.get("max_unkilled", {})
    return {key: int(value) for key, value in modules.items()}


def check_stats(
    module_key: str, stats: dict[str, Any], ratchet: dict[str, int]
) -> list[str]:
    """Reasons ``stats`` fails the gate (empty when it passes)."""
    problems: list[str] = []
    if stats["total"] <= 0:
        problems.append("the report lists zero mutants")
    if stats.get("check_was_interrupted_by_user"):
        problems.append("the mutation run was interrupted")
    count = unkilled(stats)
    limit = ratchet.get(module_key)
    if limit is None:
        problems.append(
            f"no ratchet entry for {module_key}; record {count} in {RATCHET_PATH}"
        )
    elif count > limit:
        problems.append(f"{count} unkilled mutants exceed the ratchet of {limit}")
    elif count < limit:
        print(
            f"NOTICE: {module_key} has {count} unkilled mutants, below the ratchet "
            f"of {limit}; lower {RATCHET_PATH} to {count}."
        )
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Per-module mutation baseline")
    parser.add_argument("module", nargs="?", default="ast_diff")
    parser.add_argument("--list", action="store_true", help="print modules as JSON")
    parser.add_argument("--report-dir", type=Path, help="write <module>.json here")
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    if args.list:
        print(json.dumps(list(MODULES)))
        return 0
    repo_root = Path(__file__).parent.parent.resolve()
    run_module(args.module, repo_root)
    stats = read_stats(repo_root)
    problems = check_stats(args.module, stats, load_ratchet(repo_root))
    report = {
        "module": args.module,
        "source": MODULES[args.module][0],
        "unkilled": unkilled(stats),
        "stats": stats,
        "problems": problems,
    }
    print(json.dumps(report, indent=2))
    if args.report_dir:
        args.report_dir.mkdir(parents=True, exist_ok=True)
        (args.report_dir / f"{args.module}.json").write_text(
            json.dumps(report, indent=2), encoding="utf-8"
        )
    for problem in problems:
        print(f"FAIL: {args.module}: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
