#!/usr/bin/env python3
"""RFC-0017 — per-module mutation baseline runner with a survivor ratchet.

Usage:
    uv run python scripts/run_mutation_baseline.py [module_key] [--report-dir DIR]
    uv run python scripts/run_mutation_baseline.py --list

module_key: one of :data:`MODULES` (default: ast_diff).

Runs mutmut on a single source file + its targeted tests, exports mutmut's
CI stats and fails closed:

* a mutmut ``run`` / ``results`` / ``export-cicd-stats`` failure propagates;
* no stats report, or a report with zero mutants, is a failure (a module
  whose file moved used to "pass" by producing nothing);
* the unkilled count (``survived + no_tests``) must not exceed the module's
  entry in ``tests/effectiveness/mutation_ratchet.json``. The ratchet only
  goes down: when a run beats it, lower the entry in the same PR. A module
  without an entry fails and prints the number to record.

NOTE: mutmut uses os.fork — Linux only (ubuntu-latest in CI).
"""

